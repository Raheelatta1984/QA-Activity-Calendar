/**
 * Generates docs/ID-CATALOGUE.md from the live tabs/sections configuration so
 * enhancement requests can quote an exact, stable ID.
 */
import fs from "node:fs";
import path from "node:path";
import { all, initDb } from "../lib/db";

initDb();
const tabs = all<any>(`SELECT * FROM tabs ORDER BY sort_order`);
const sections = all<any>(`SELECT * FROM sections ORDER BY tab_id, sort_order`);

const lines: string[] = [
  "# Tab & section ID catalogue",
  "",
  "Every tab and section exposes a stable identifier in the UI. Quote these IDs in",
  "enhancement requests and What's New entries so a change is unambiguous.",
  "",
  "Generated by `npm run catalogue`. IDs are primary keys — never reuse or rename",
  "them for a new surface; add a new row instead.",
  "",
  "| Tab ID | Label | Group | Min role | Enabled | Sections |",
  "| --- | --- | --- | --- | --- | --- |",
];

for (const tab of tabs) {
  const tabSections = sections.filter((s) => s.tab_id === tab.id);
  lines.push(
    `| \`${tab.id}\` | ${tab.label} | ${tab.group_name} | ${tab.min_role} | ${tab.enabled ? "yes" : "no"} | ${tabSections.length} |`
  );
}

lines.push("", "## Sections", "");
for (const tab of tabs) {
  const tabSections = sections.filter((s) => s.tab_id === tab.id);
  if (!tabSections.length) continue;
  lines.push(`### ${tab.label} — \`${tab.id}\``, "");
  lines.push("| Section ID | Label | Enabled | Description |", "| --- | --- | --- | --- |");
  for (const section of tabSections) {
    lines.push(
      `| \`${section.id}\` | ${section.label} | ${section.enabled ? "yes" : "no"} | ${(section.description ?? "").replace(/\|/g, "\\|")} |`
    );
  }
  lines.push("");
}

const out = path.join(process.cwd(), "docs", "ID-CATALOGUE.md");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join("\n"), "utf8");
console.log(`Wrote ${out} — ${tabs.length} tabs, ${sections.length} sections.`);
